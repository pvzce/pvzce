/**
 * The four rhythm tiers, as data: the shape of a chart and the levels it is written into.
 *
 * <p>One track, one tempo, four densities. The generator lives in {@code common} rather than in the
 * editor because both sides need the same answer: the editor writes the files with it, and the
 * shipped levels were written with it, so "what a tier is" has one definition - the same reason
 * every other piece of content has a single home.
 *
 * <p>The charts are generated rather than transcribed. A rhythm chart is normally an author's
 * note-by-note work, and this project has no audio analysis to derive one from; what it does have
 * is a tempo and a difficulty, and a deterministic pattern from those two is a chart that can be
 * regenerated byte for byte. That is the honest shape of the feature: the levels are playable, the
 * numbers are the level file's, and a hand-written chart drops into the same block whenever
 * somebody writes one.
 */
